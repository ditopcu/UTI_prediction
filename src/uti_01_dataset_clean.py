def parse_culture_result(result_str):
    # Handle negative or zero results
    if pd.isna(result_str) or str(result_str).strip() in ['0', 'Negativo']:
        return pd.Series({'Bacteria': 'Negativo', 'Colony_Count': '', 'Sensible_Antibiotics': '', 'Resistant_Antibiotics': ''})

    parts = str(result_str).split('\n')
    bacteria = parts[0].strip()

    colony_count = ''
    sensible = []
    resistant = []
    current_list = None

    for part in parts[1:]:
        cleaned_part = part.strip()

        # Extract colony count
        if 'UFC/ml' in cleaned_part:
            colony_count = cleaned_part
            continue

        # Skip empty lines or other non-antibiotic metadata
        if not cleaned_part or 'CEPA' in cleaned_part:
            continue

        if 'Sensible' in cleaned_part:
            current_list = sensible
        elif 'Resistente' in cleaned_part:
            current_list = resistant
        else:
            if current_list is not None:
                current_list.append(cleaned_part)

    return pd.Series({
        'Bacteria': bacteria,
        'Colony_Count': colony_count,
        'Sensible_Antibiotics': ', '.join(sensible),
        'Resistant_Antibiotics': ', '.join(resistant)
    })

