"""### 4. Optuna ile Hiperparametre Optimizasyonu (En İyi Model: EC Dahil)"""

import optuna
from catboost import CatBoostClassifier
from sklearn.metrics import roc_auc_score

# Optuna i&#231;in objective fonksiyonu
def objective(trial):
    params = {
        'iterations': trial.suggest_int('iterations', 200, 1000),
        'learning_rate': trial.suggest_float('learning_rate', 1e-3, 0.3, log=True),
        'depth': trial.suggest_int('depth', 4, 10),
        'l2_leaf_reg': trial.suggest_float('l2_leaf_reg', 1e-3, 10.0, log=True),
        'border_count': trial.suggest_int('border_count', 32, 255),
        'bagging_temperature': trial.suggest_float('bagging_temperature', 0.0, 1.0),
        'od_type': 'Iter',
        'od_wait': 50,
        'random_seed': 42,
        'verbose': False
    }

    # Modeli oluştur ve eğitt
    model = CatBoostClassifier(**params)
    model.fit(
        X_train_boruta_ec, y_train,
        eval_set=(X_test_boruta_ec, y_test),
        early_stopping_rounds=50,
        verbose=False
    )

    # Test seti &#252;zerinde AUC hesapla
    y_pred_proba = model.predict_proba(X_test_boruta_ec)[:, 1]
    auc = roc_auc_score(y_test, y_pred_proba)
    return auc

# &#199;alışmayı başlat (Maximum AUC hedefleniyor)
study = optuna.create_study(direction='maximize')
study.optimize(objective, n_trials=30)  # İhtiyaca g&#246;re deneme sayısını (n_trials) artırabilirsiniz

print("\n--- Optuna Optimizasyon Sonu&#231;ları ---")
print("En iyi parametreler:", study.best_params)
print("En iyi Test ROC AUC:", study.best_value)

# En iyi parametrelerle final modelini oluştur ve eğitt
best_params = study.best_params
best_params['random_seed'] = 42
best_params['verbose'] = 100  # Eğitim s&#252;recini g&#246;rmek i&#231;in

