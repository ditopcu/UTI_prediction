from sklearn.metrics import roc_auc_score, average_precision_score
import pandas as pd

def get_auc_metrics(model, X_train, y_train, X_test, y_test, X_other, y_other, model_name):
    metrics = []

    # Veri setleri ve etiketleri listele
    datasets = [
        ('Train', X_train, y_train),
        ('Test', X_test, y_test),
        ('Other', X_other, y_other)
    ]

    for split_name, X_data, y_data in datasets:
        # Sınıf olasılıklarını al (Pozitif sınıf: 1)
        y_pred_proba = model.predict_proba(X_data)[:, 1]

        roc_auc = roc_auc_score(y_data, y_pred_proba)
        pr_auc = average_precision_score(y_data, y_pred_proba)

        metrics.append({
            'Model': model_name,
            'Veri Seti': split_name,
            'ROC AUC': round(roc_auc, 4),
            'PR AUC': round(pr_auc, 4)
        })

    return metrics

