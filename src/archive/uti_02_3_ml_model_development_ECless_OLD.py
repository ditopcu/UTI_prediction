"""Boruta uses a `RandomForestClassifier` as the base estimator and expects NumPy arrays (not pandas DataFrames)."""

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from boruta import BorutaPy

# Ensure 'FECHA' (date) column is numerical before creating numpy arrays
# This converts datetime objects to seconds since the Unix epoch
if 'FECHA' in X_train.columns and pd.api.types.is_datetime64_any_dtype(X_train['FECHA']):
    X_train['FECHA'] = X_train['FECHA'].astype(int) / 10**9
if 'FECHA' in X_test.columns and pd.api.types.is_datetime64_any_dtype(X_test['FECHA']):
    X_test['FECHA'] = X_test['FECHA'].astype(int) / 10**9

# Boruta requires numpy arrays, created from the (potentially modified) DataFrames
X_train_np = X_train.values
y_train_np = y_train.values

# Define the base Random Forest classifier
rf = RandomForestClassifier(n_jobs=-1, class_weight='balanced', max_depth=5)

# Initialize Boruta feature selector
feat_selector = BorutaPy(rf, n_estimators='auto', verbose=2, random_state=42)

# Fit Boruta (this may take some time depending on the dataset size)
feat_selector.fit(X_train_np, y_train_np)

# Check selected features
selected_features = X_train.columns[feat_selector.support_].tolist()
tentative_features = X_train.columns[feat_selector.support_weak_].tolist()

print(f"\nNumber of selected features: {len(selected_features)}")
print(f"Selected features: {selected_features}")
print(f"\nNumber of tentative features: {len(tentative_features)}")
print(f"Tentative features: {tentative_features}")

"""### 2.1 Visualize Boruta results"""

import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd

# Create a list of statuses based on Boruta output
statuses = []
for i in range(len(X_train.columns)):
    if feat_selector.support_[i]:
        statuses.append('Confirmed')
    elif feat_selector.support_weak_[i]:
        statuses.append('Tentative')
    else:
        statuses.append('Rejected')

# To get continuous importance values, we can use the feature_importances_
# from the Random Forest model that Boruta used.
# We quickly fit it on the full training set to get the importances.
rf.fit(X_train_np, y_train_np)
importances = rf.feature_importances_

# Create a DataFrame for plotting
boruta_df = pd.DataFrame({
    'Feature': X_train.columns,
    'Importance': importances,
    'Status': statuses
})

# Sort by importance (highest is best)
boruta_df = boruta_df.sort_values(by=['Importance', 'Feature'], ascending=[False, True])

# Plot the features
plt.figure(figsize=(12, 10))
sns.barplot(x='Importance', y='Feature', data=boruta_df,
            hue='Status', dodge=False,
            palette={'Confirmed': 'green', 'Tentative': 'orange', 'Rejected': 'red'})
