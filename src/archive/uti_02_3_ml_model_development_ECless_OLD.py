# Function to generate annotations with counts and percentages
def get_annot(cm):
    counts = ["{0:0.0f}".format(value) for value in cm.flatten()]
    percentages = ["{0:.1%}".format(value) for value in cm.flatten()/np.sum(cm)]
    labels = [f"{v1}\n({v2})" for v1, v2 in zip(counts, percentages)]
    return np.asarray(labels).reshape(cm.shape)

