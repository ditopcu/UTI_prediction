"""### 4.4 AutoGluon — train with Youden's J as eval metric

A custom AutoGluon scorer for Youden's index (sensitivity + specificity − 1) is defined and used as `eval_metric`.
"""

from autogluon.tabular import TabularPredictor
from autogluon.core.metrics import make_scorer
from sklearn.metrics import confusion_matrix
import numpy as np

# Define Youden's J statistic
def youden_index(y_true, y_pred):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    sensitivity = tp / (tp + fn) if (tp + fn) > 0 else 0
    specificity = tn / (tn + fp) if (tn + fp) > 0 else 0
    return sensitivity + specificity - 1

# Create an AutoGluon custom scorer
youden_scorer = make_scorer(
    name='youden',
    score_func=youden_index,
    optimum=1,
    greater_is_better=True
)

# Train a new TabularPredictor using the custom Youden metric
# We specify a new path so it doesn't overwrite the previous 'recall' model
predictor_youden = TabularPredictor(
    label=label,
    eval_metric=youden_scorer,
    path='AutogluonModels/ag_youden'
).fit(
    train_data,
    time_limit=900,
    presets='best_quality'
)

# Evaluate the new predictor on the test data
print("--- AutoGluon (Youden Metric) Evaluation Results ---")
results_youden = predictor_youden.evaluate(test_data)
display(results_youden)

